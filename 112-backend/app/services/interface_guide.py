def guide_text(task, target, goal, explanation, solution):
    if task.endswith(".finished"):
        return f"{goal}\n\n{explanation}\n\n{solution}"
    instruction = INSTRUCTIONS.get(target, explanation)
    if task.startswith("features."):
        instruction = (
            "Выберите значение в подсвеченном признаке. "
            "Ниже могут появиться дополнительные вопросы. "
            "Повторный клик отменяет выбор; в некоторых признаках допустимо несколько вариантов."
        )
    return f"{goal}\n\n{instruction}\n\n{solution}"
